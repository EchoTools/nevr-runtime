#pragma once

// Combat's clocks stand still while PAUSE is on (#600, EchoCombat slice 7 PR 8; he_is_the_cat's fix_clock_pause.py,
// read as text, reconstructed here as hooks on Combat's game-mode script, mp_combat_server_state 6fa8cc9cd721a563).
//
// The script keeps its own clocks in its globals, which the war room's "PREPARE FOR ROUND" HUD and the round flow read:
//   game_timer       globals +0xA8  (float seconds)
//   lobbylock_timer  globals +0xB0
//   countdown_timer  globals +0xB4
// A node reaches its globals through its context: node -> [node] (the context, a qword) -> [context+0x68] (the
// globals, a qword). Fifteen functions count a clock down, each by the frame time it reads once, as
// `cvtsi2ss xmm, qword [context+0x50]` (microseconds, then `divss` by 1e6):
//  - 8 expressions, `float (node)`, return max(timer - dt, 0): game_timer at 0x28CA0, lobbylock_timer at 0x23300, and
//    countdown_timer at 0x220A0, 0x22A40, 0x26500, 0x26D70, 0x26F00, 0x28030. The game_timer expression also asks the
//    engine about the node (two engine calls) and returns the timer unchanged when the answer says so.
//  - 7 nodes, `u64 (node)`, write max(timer - dt, 0) back and return 0, or, when the node's byte +0xDB is set, write
//    nothing and return -1: lobbylock_timer at 0xFAB0, countdown_timer at 0xE5C0, 0xF220, 0x12B70, 0x134B0, 0x137D0,
//    0x145E0.
// max(x, 0) is the game's `comiss x, 0; jae`: x when x >= 0, else 0, so a NaN gives 0 and -0.0 stays -0.0.
//
// His patch makes each of those 15 frame-time loads give 0 while VeilNet's PAUSE byte (RULES mailbox +0x2E) is not 0
// (1 paused, 2 the resume countdown), and leaves the frame time everywhere else alone. Here each function is wrapped:
// with PAUSE 0 it runs as shipped; otherwise the wrapper returns what the function gives with a frame time of 0, without
// calling it (an expression returns max(timer, 0); a node writes max(timer, 0) and returns 0, or returns -1 when +0xDB
// is set), except the game_timer expression, which is called for its engine answer, and whose result is replaced by
// max(timer, 0) when it is not the timer unchanged. The arena game-mode script (mp_game_server_state) has the same clocks;
// Combat does not count with it, and it is left alone, as his patch leaves it.
//
// Each row pins the function's bytes from its start through the timer read, the code the paused path is written from.

