// In Combat, the capture point unlocks at the RULES page's unlock time, and its unlock countdown stands still while PAUSE
// is on (#600, EchoCombat slice 7 PR 10b-2; he_is_the_cat's fix_capture_points.py, read as text, the capture point half
// of its time rows, reconstructed here as hooks on the capture point script, b7d10bcffcb2a780). The game-mode half,
// which writes T to the RULES mailbox, is capture_time.h.
//
// The capture point script keeps its unlock time in capture_point_lock_time (globals +0xEC, a float: the seconds the
// countdown starts from; the page shows it in its minutes row, so his patch takes T / 60, the page's top row), which
// the map's JSON, a bulk loader and two set-by-name functions write. While T (RULES mailbox +0x08) is set, his patch
// makes every read of it give float(int(T) / 60). The script reads +0xEC in five places, which are
// all the reads of +0xEC in the file:
//  - the unlock countdown node 0x10030 (`u64 (node)`): countdown +0xDC = lock - (now / 1e6 - start +0xF4), with now the
//    context's qword +0x58 in microseconds; with the node's byte +0xDB set it writes nothing and returns -1;
//  - the expression 0x1F130 (`float (node)`): lock - elapsed, computed the same way;
//  - the get-by-name 0x178F0 (`(context, name, type, out)`), for the name 0x3ACAD89454787129, at 0x179E2;
//  - the state pack 0x8AC0 (`(context, out, ...)`), which copies the globals out, at 0x91D8;
//  - the typed getter 0x4BC0 (`(globals, name, type, out)`, reached by pointer), which for type 1 and the name
//    0xE32DC7CC8D8B41B6 copies +0xE4..+0xF0 out, at 0x4CF1.
// Here each of the five is wrapped. While T is set, the lock time at +0xEC is float(int(T) / 60) while it runs, and the
// map's own value is put back after it (the typed getter only on the path that reads it; on its other paths the pointer
// is another structure). The writers are left alone: no read sees what they store while T is set.
//
// While PAUSE (+0x2E) is not 0, his patch also moves the countdown's start so the countdown stands still, on server and
// clients alike (the unlock voice line is client-side), unless the node's +0xDB is set: x1 = lock - countdown,
// start = (elapsed + start) - x1, countdown = lock - x1. Here the countdown node computes exactly that, in that order,
// while PAUSE is on, and does not call the stock node; an unlocked point keeps its negative countdown.
//
// The countdown node and the expression are pinned whole or through their read; the three getters are pinned at their
// heads and, with pinned rows, at their reads.

