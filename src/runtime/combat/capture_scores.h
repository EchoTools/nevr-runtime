// Private Combat matches: the RULES page's starting scores become the capture points' points (#600, EchoCombat slice 7
// PR 10a; he_is_the_cat's fix_capture_points.py, read as text, its starting-score half, reconstructed here as hooks on
// two scripts). The other half of his tool, the RULES time rows, is not here.
//
// The podium terminal's RULES page sets a starting score per team. Combat's game-mode script (mp_combat_server_state,
// 6fa8cc9cd721a563) keeps those values in its globals, blue_point_score at +0xF0 and red_point_score at +0xD0 (int32,
// read as `mov ecx, dword [globals+0xF0]` at 0xD4FB and `mov ecx, dword [globals+0xD0]` at 0xCBDB), and six nodes
// publish them (0xCB60, 0xCCA0, 0xD480, 0x16380, 0x16A60, 0x184A0), on each -/+ press and at match start. But the
// capture point script (b7d10bcffcb2a780) keeps each team's points itself, blueteamcharge at +0xF8 and
// orangeteamcharge at +0xF0 (floats), and starts every round from 0, so the setting did nothing.
//
// The two scripts are joined through the RULES mailbox (rules_state.h: +0x00 blue, +0x04 orange, as floats):
//  - each publish node first copies float(blue_point_score) and float(red_point_score) to the mailbox;
//  - in the capture point script, everything that zeroes a team's points loads the team's starting score instead:
//    the two reset nodes (0x14780 blue, 0x14E90 orange: `mov dword [globals+charge], 0`), the same two resets
//    inlined in the node dispatcher (0xB2D0, for node ids 0x50865EFB at 0xB9C1 and 0x4B6B0B1F at 0xB8DE; the id is
//    the node's qword +0x10), and the variable initializer (0x1CDE0, run when the script is set up for a round, which
//    writes both charges 0 at 0x1CE57 and 0x1CE6D and reads neither after);
//  - the two nodes that zero the HUD's score netvars at round start (0xFA40 blue, 0x11180 orange) publish the starting
//    score / 100 instead (the HUD shows points / 100 as a percentage), so the score shows before a team first charges.
// A mailbox of zeros is the stock behaviour.
//
// Here the publish nodes, the reset nodes, the dispatcher and the initializer are wrapped (the copy before the node;
// the starting score written after the reset, after the dispatcher for those two ids, after the initializer). A HUD
// node is rebuilt in C++ while its team's starting score is not 0: it fills the record the stock node fills on its stack
// (0x30 bytes: +0x00 qword 0, +0x08 byte 0, +0x10 qword -1, +0x18 qword -1, +0x20 the netvar's symbol, +0x28 the float
// value, +0x2C byte 0) and calls the script's own setter at 0x2640 with it and the node, as the stock node does, with
// the value score / 100 instead of 0. The dispatcher's two inline resets are pinned rows: their bytes are checked with
// the script's other rows, and nothing is installed there.

