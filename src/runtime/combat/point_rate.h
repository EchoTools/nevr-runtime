// Capture points: POINT RATE, and the points stand still while PAUSE is on (#600, EchoCombat slice 7 PR 9;
// he_is_the_cat's fix_point_rate.py, read as text, reconstructed here as hooks on the capture point script,
// b7d10bcffcb2a780).
//
// The script raises each team's points in an expression, `float (node)`, blue at 0x230A0 and orange at 0x223F0. A node
// reaches its globals through its context (node -> [node] -> [context+0x68]), and the expression returns
//   clamp(charge + (dt * k1) * k2, 0, required)
//   charge    the team's points: blue globals +0xF8, orange +0xF0 (float)
//   dt        the frame time: `cvtsi2ss qword [context+0x50]` (microseconds) divided by 1e6 (the constant at 0x2A1D8)
//   k1        1.0 (the constant at 0x2A194) when the engine's answer is the team's symbol, else globals +0xE4. The
//             answer is the field whose id setup_bindings stores at 0x2C6B4 (a dword, `mov edx, dword [rip]`),
//             read through the engine accessor the script calls at slot 0x2CB58 into a qword at [rsp+0x28] and
//             compared in full: blue 0xC8C33E48387F0BB5, orange 0x41D2C82F1B2D001B.
//   k2        globals +0xE0 when the byte globals +0x11B is set, else 1.0
//   required  globals +0xFC (float); the clamp is the game's: above required gives required, below 0 gives 0, and
//             anything else, NaN included, is kept.
// Blue multiplies k2 * (dt * k1) and orange (k1 * dt) * k2; IEEE multiplication commutes exactly, so both are one
// expression here.
//
// His patch multiplies dt, right after its divide, by mailbox +0x2D / 4 (VeilNet's POINT RATE, in quarters: 4 is x1,
// 0 is not set and leaves dt alone), and makes it 0 while PAUSE (mailbox +0x2E) is not 0. Here each expression is
// wrapped. With PAUSE 0 and POINT RATE 0 it runs as shipped. Otherwise the wrapper calls it, so the engine is asked as
// the game asks it, and while it runs the accessor slot is replaced by one that records the answer (for that field
// only, on that thread); then the wrapper returns the expression's value computed with dt scaled, or 0 while paused,
// in the order his patch computes it. An expression whose answer was not recorded keeps the game's value. The
// accessor's other callers (34 more: 36 `call [rip+0x2CB58]` in the script, the two expressions' among them) are
// untouched.
//
// Each row pins the expression from its start through its read of required, the code the value is computed from.

