// The RULES page's time rows, in Combat, set the capture point's times (#600, EchoCombat slice 7 PR 10b-1; he_is_the_cat's
// fix_capture_points.py, read as text, the game-mode half of its time rows, reconstructed here as hooks on Combat's
// game-mode script, mp_combat_server_state 6fa8cc9cd721a563). The capture point script's half (its unlock time, and the
// unlock countdown standing still while PAUSE is on) is not here.
//
// The podium's RULES page has two time rows, round minutes and seconds. The game-mode script keeps them as one MM:SS
// value in game_timer (globals +0xA8, a float, read as `cvttss2si reg, dword [globals+0xA8]`), which is also Combat's
// own match clock. In Combat that value is T = the point's unlock time * 60 + its capture time instead, kept in the
// RULES mailbox (+0x08, a float; unset is read as 45 * 60 + 4, both capture point maps' own times), and each change also
// writes the capture time, T mod 60, at +0x0C, which VeilNet reads. The clock itself is never touched.
//
// Nine functions read or write the page's value, each reached by one tail jump from the script's node dispatcher:
//  - the four row handlers, which write it: two for the seconds row, 0xFF50 (its press raises the seconds, at most to
//    59) and 0x10A20, which read it and write it; two for the minutes row, 0xFA60 and 0x14FB0, which write what the
//    helper they call returns (0x23240 and 0x28930, each called by its handler only, which read it);
//  - five nodes that read it to publish it: 0x16160, 0x13E00, 0x12860, 0x11F90, 0x16050 (0x16160 publishes int(value)
//    as the netvar 0x5B748A2B4792DD2D).
// His patch rewrites each read to read T and each write to write T and the capture time. Here each function is wrapped:
// before it runs, its value at +0xA8 is T (or 2704 while T is unset); after it, the clock is put back, and a handler
// that wrote (it returns 0, not the -1 it returns when the node's +0xDB is set) stores what it wrote as T, and T mod 60
// as the capture time. A helper reads under its handler's wrap. Each row pins its function from its start through its
// last +0xA8 access, and the two helpers are pinned rows.

