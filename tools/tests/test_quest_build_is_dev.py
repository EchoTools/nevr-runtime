"""#758: only a development build may download game data, so `kIsDev` must be false for a release.

`src/quest/sentinel/entry.cpp` sets `options.allow_fetch = nevr_build::kIsDev`, and `nevr_build::kIsDev` is generated by
`cmake/nevr_build_info.cmake`. A release is a CI build exactly on a release tag (`cmake/set_project_version_from_git.cmake`);
every other build is a development build. This test runs the real generator in a scratch git repository: once as a
release (the CI variables of a tag build, HEAD at the tag) and once as a development build, and reads the generated header.
"""

import os
import shutil
import subprocess
import tempfile
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
FILES = ("nevr_build_info.cmake", "nevr_build_info.h.in", "set_project_version_from_git.cmake")
GIT_ENV = {
    "GIT_AUTHOR_NAME": "t", "GIT_AUTHOR_EMAIL": "t@example.invalid",
    "GIT_COMMITTER_NAME": "t", "GIT_COMMITTER_EMAIL": "t@example.invalid",
}


@unittest.skipUnless(shutil.which("cmake") and shutil.which("git"), "needs cmake and git")
class KIsDevFollowsTheTag(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.repo = Path(self.tmp.name)
        (self.repo / "cmake").mkdir()
        for name in FILES:
            shutil.copy(ROOT / "cmake" / name, self.repo / "cmake" / name)
        (self.repo / "gen.cmake").write_text(
            "include(${CMAKE_SOURCE_DIR}/cmake/nevr_build_info.cmake)\nnevr_generate_build_info(${CMAKE_SOURCE_DIR})\n"
        )
        env = {**os.environ, **GIT_ENV}
        for cmd in (["init", "-q"], ["add", "-A"], ["commit", "-q", "-m", "x"], ["tag", "-a", "v5.5.0", "-m", "x"]):
            subprocess.run(["git", *cmd], cwd=self.repo, env=env, check=True, capture_output=True)

    def tearDown(self):
        self.tmp.cleanup()

    def header(self, **ci):
        env = {k: v for k, v in os.environ.items() if not k.startswith("GITHUB_")}
        env.update(ci)
        out = self.repo / "generated"
        shutil.rmtree(out, ignore_errors=True)
        subprocess.run(["cmake", "-P", "gen.cmake"], cwd=self.repo, env=env, check=True, capture_output=True)
        return (out / "nevr_build_info.h").read_text()

    def test_a_tag_build_on_the_tag_is_not_a_development_build(self):
        text = self.header(GITHUB_ACTIONS="true", GITHUB_REF_TYPE="tag", GITHUB_REF_NAME="v5.5.0")
        self.assertIn('kVersion = "5.5.0"', text)
        self.assertIn("kIsDev = false;", text)

    def test_any_other_build_is_a_development_build(self):
        text = self.header()
        self.assertIn("-dev.", text)
        self.assertIn("kIsDev = true;", text)

    def test_a_tag_build_of_another_tag_name_is_a_development_build(self):
        text = self.header(GITHUB_ACTIONS="true", GITHUB_REF_TYPE="tag", GITHUB_REF_NAME="v9.9.9")
        self.assertIn("kIsDev = true;", text)


if __name__ == "__main__":
    unittest.main()
