"""#758: only a development build may download game data, so `kIsDev` must be false for a release.

A release is a CI build of a release tag: the tag ref the build runs on is a final tag (`vX.Y.Z`) or a release-candidate
tag (`vX.Y.Z-rc.N`) and points at the commit being built. Other tags on the same commit change nothing: a commit
carrying an rc tag and the final tag, or two final tags, builds as a release from either tag's ref.

`src/quest/sentinel/entry.cpp` sets `options.allow_fetch = nevr_build::kIsDev`, and `nevr_build::kIsDev` is generated by
`cmake/nevr_build_info.cmake`. A release is a CI build exactly on a release tag (`cmake/set_project_version_from_git.cmake`);
every other build is a development build. This test runs the real generator in a scratch git repository: once as a
release (the CI variables of a tag build, HEAD at the tag) and once as a development build, and reads the generated header.
"""

import os
import shutil
import subprocess
import tempfile
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
FILES = ("nevr_build_info.cmake", "nevr_build_info.h.in", "set_project_version_from_git.cmake")
GIT_ENV = {
    "GIT_AUTHOR_NAME": "t", "GIT_AUTHOR_EMAIL": "t@example.invalid",
    "GIT_COMMITTER_NAME": "t", "GIT_COMMITTER_EMAIL": "t@example.invalid",
}


@unittest.skipUnless(shutil.which("cmake") and shutil.which("git"), "needs cmake and git")
class KIsDevFollowsTheTag(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.repo = Path(self.tmp.name)
        (self.repo / "cmake").mkdir()
        for name in FILES:
            shutil.copy(ROOT / "cmake" / name, self.repo / "cmake" / name)
        (self.repo / "gen.cmake").write_text(
            "include(${CMAKE_SOURCE_DIR}/cmake/nevr_build_info.cmake)\nnevr_generate_build_info(${CMAKE_SOURCE_DIR})\n"
        )
        env = {**os.environ, **GIT_ENV}
        for cmd in (["init", "-q"], ["add", "-A"], ["commit", "-q", "-m", "x"], ["tag", "-a", "v5.5.0", "-m", "x"]):
            subprocess.run(["git", *cmd], cwd=self.repo, env=env, check=True, capture_output=True)

    def tearDown(self):
        self.tmp.cleanup()

    def header(self, **ci):
        env = {k: v for k, v in os.environ.items() if not k.startswith("GITHUB_")}
        env.update(ci)
        out = self.repo / "generated"
        shutil.rmtree(out, ignore_errors=True)
        subprocess.run(["cmake", "-P", "gen.cmake"], cwd=self.repo, env=env, check=True, capture_output=True)
        return (out / "nevr_build_info.h").read_text()

    def test_a_tag_build_on_the_tag_is_not_a_development_build(self):
        text = self.header(GITHUB_ACTIONS="true", GITHUB_REF_TYPE="tag", GITHUB_REF_NAME="v5.5.0")
        self.assertIn('kVersion = "5.5.0"', text)
        self.assertIn("kIsDev = false;", text)

    def test_any_other_build_is_a_development_build(self):
        text = self.header()
        self.assertIn("-dev.", text)
        self.assertIn("kIsDev = true;", text)

    def test_a_tag_build_of_another_tag_name_is_a_development_build(self):
        text = self.header(GITHUB_ACTIONS="true", GITHUB_REF_TYPE="tag", GITHUB_REF_NAME="v9.9.9")
        self.assertIn("kIsDev = true;", text)

    def git(self, *cmd):
        subprocess.run(["git", "-c", "tag.gpgSign=false", "-c", "commit.gpgSign=false", *cmd], cwd=self.repo,
                       env={**os.environ, **GIT_ENV}, check=True, capture_output=True)

    def tag_build(self, name, **ci):
        return self.header(GITHUB_ACTIONS="true", GITHUB_REF_TYPE="tag", GITHUB_REF_NAME=name, **ci)

    def test_a_commit_with_an_rc_tag_and_the_final_tag_is_a_release_from_the_rc_tag_ref(self):
        self.git("tag", "-a", "v5.5.0-rc.1", "-m", "x")
        self.assertIn("kIsDev = false;", self.tag_build("v5.5.0-rc.1"))

    def test_a_commit_with_an_rc_tag_and_the_final_tag_is_a_release_from_the_final_tag_ref(self):
        self.git("tag", "-a", "v5.5.0-rc.1", "-m", "x")
        self.assertIn("kIsDev = false;", self.tag_build("v5.5.0"))

    def test_a_commit_with_two_final_tags_is_a_release_from_either_tag_ref(self):
        self.git("tag", "v5.5.1")  # lightweight; `git describe` prefers the annotated v5.5.0
        self.assertIn("kIsDev = false;", self.tag_build("v5.5.1"))
        self.assertIn("kIsDev = false;", self.tag_build("v5.5.0"))

    def test_a_tag_ref_that_does_not_point_at_the_built_commit_is_a_development_build(self):
        self.git("tag", "-a", "v5.5.1", "-m", "x")
        (self.repo / "later.txt").write_text("later\n")
        self.git("add", "-A")
        self.git("commit", "-q", "-m", "later")
        self.assertIn("kIsDev = true;", self.tag_build("v5.5.1"))

    def test_a_tag_name_that_is_not_a_release_or_rc_tag_is_a_development_build(self):
        for name in ("v5.5.0-beta.1", "v5.5.0-rc", "v5.5.0-rc.0", "v5.5", "5.5.0", "v5.5.0-dev.1", "v5.5.0-rc.1+x"):
            self.git("tag", name)
            self.assertIn("kIsDev = true;", self.tag_build(name), name)

    def test_a_tag_name_outside_ci_or_a_branch_ref_is_a_development_build(self):
        self.assertIn("kIsDev = true;", self.header(GITHUB_REF_TYPE="tag", GITHUB_REF_NAME="v5.5.0"))
        self.assertIn("kIsDev = true;", self.header(GITHUB_ACTIONS="true", GITHUB_REF_TYPE="branch", GITHUB_REF_NAME="v5.5.0"))
        self.assertIn("kIsDev = true;", self.header(GITHUB_ACTIONS="false", GITHUB_REF_TYPE="tag", GITHUB_REF_NAME="v5.5.0"))


if __name__ == "__main__":
    unittest.main()
