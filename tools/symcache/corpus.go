package main

import (
	"encoding/json"
	"errors"
	"fmt"
	"io"
	"regexp"
	"sort"
	"strconv"
	"strings"
)

// Corpus maps a CSymbol64 hash to the symbol name it was computed from.
type Corpus map[uint64]string

var hashKeyPattern = regexp.MustCompile(`^0x[0-9a-f]{16}$`)

// LoadCorpus parses a flat {"0x<16 hex>": "name"} JSON object and rejects
// anything the generated cache cannot represent: malformed JSON, a key that is
// not exactly 0x followed by 16 lowercase hex digits, a non-string value, or a
// duplicate key.
func LoadCorpus(r io.Reader) (Corpus, error) {
	decoder := json.NewDecoder(r)
	token, err := decoder.Token()
	if err != nil {
		return nil, fmt.Errorf("parse: %w", err)
	}
	if delim, ok := token.(json.Delim); !ok || delim != '{' {
		return nil, errors.New("parse: top level is not a JSON object")
	}

	corpus := Corpus{}
	for decoder.More() {
		token, err := decoder.Token()
		if err != nil {
			return nil, fmt.Errorf("parse key: %w", err)
		}
		key, ok := token.(string)
		if !ok || !hashKeyPattern.MatchString(key) {
			return nil, fmt.Errorf("key %q is not ^0x[0-9a-f]{16}$", key)
		}
		hash, err := strconv.ParseUint(key[2:], 16, 64)
		if err != nil {
			return nil, fmt.Errorf("key %q: %w", key, err)
		}

		var value any
		if err := decoder.Decode(&value); err != nil {
			return nil, fmt.Errorf("parse value for %s: %w", key, err)
		}
		name, ok := value.(string)
		if !ok {
			return nil, fmt.Errorf("value for %s is %T, want string", key, value)
		}
		if _, duplicate := corpus[hash]; duplicate {
			return nil, fmt.Errorf("duplicate key %s", key)
		}
		corpus[hash] = name
	}

	if _, err := decoder.Token(); err != nil {
		return nil, fmt.Errorf("parse: %w", err)
	}
	var trailing any
	if err := decoder.Decode(&trailing); err != io.EOF {
		return nil, errors.New("trailing data after the JSON object")
	}
	if len(corpus) == 0 {
		return nil, errors.New("no entries")
	}
	return corpus, nil
}

// ValidateOptions controls the pin-to-pin checks. PreviousCount is the entry
// count at the previous pin; zero means there is no previous pin and the count
// delta is not checked.
type ValidateOptions struct {
	PreviousCount int
}

// ValidateCorpus re-hashes every name and requires the key to match, then
// requires the entry count to be within 20% of the previous pin's count.
func ValidateCorpus(corpus Corpus, options ValidateOptions) error {
	if len(corpus) == 0 {
		return errors.New("validation: no entries")
	}

	bad := make([]string, 0, 5)
	for hash, name := range corpus {
		computed := csymbol64(name)
		if computed != hash {
			bad = append(bad, fmt.Sprintf("%#016x %q hashes to %#016x", hash, name, computed))
			if len(bad) == 5 {
				break
			}
		}
	}
	if len(bad) > 0 {
		return fmt.Errorf("validation: %s", strings.Join(bad, "; "))
	}

	if options.PreviousCount > 0 {
		previous := options.PreviousCount
		delta := len(corpus) - previous
		if delta < 0 {
			delta = -delta
		}
		if delta*5 > previous {
			return fmt.Errorf("validation: %d entries is more than 20%% away from the previous pin's %d", len(corpus), previous)
		}
	}
	return nil
}

// WriteGenerated writes the C++ table deterministically: sorted by hash, with
// the pin recorded in the header so an unchanged pin can be detected.
func WriteGenerated(w io.Writer, corpus Corpus, sourceName, pin string) error {
	hashes := make([]uint64, 0, len(corpus))
	for hash := range corpus {
		hashes = append(hashes, hash)
	}
	sort.Slice(hashes, func(i, j int) bool { return hashes[i] < hashes[j] })

	fmt.Fprintln(w, "// AUTO-GENERATED by tools/symcache — DO NOT EDIT")
	fmt.Fprintf(w, "// Source: Dualgame/echo-symbols %s @ %s\n", sourceName, pin)
	fmt.Fprintln(w)
	fmt.Fprintln(w, `#include "runtime/log/symcache.h"`)
	fmt.Fprintln(w)
	fmt.Fprintln(w, "namespace evr {")
	fmt.Fprintln(w)
	fmt.Fprintf(w, "// Total entries: %d\n", len(hashes))
	fmt.Fprintln(w)
	fmt.Fprintln(w, "extern const SymCacheEntry kSymCacheData[] = {")
	for _, hash := range hashes {
		fmt.Fprintf(w, "    {0x%016xULL, \"%s\"},\n", hash, cEscape(corpus[hash]))
	}
	fmt.Fprintln(w, "};")
	fmt.Fprintln(w)
	fmt.Fprintf(w, "extern const int kSymCacheCount = %d;\n", len(hashes))
	fmt.Fprintln(w)
	fmt.Fprintln(w, "}  // namespace evr")
	return nil
}

// cEscape renders a name as a C string literal body. Non-printable and
// non-ASCII bytes use three-digit octal escapes, which cannot swallow a
// following digit the way \x does.
func cEscape(name string) string {
	var builder strings.Builder
	for i := 0; i < len(name); i++ {
		c := name[i]
		switch c {
		case '\\':
			builder.WriteString(`\\`)
		case '"':
			builder.WriteString(`\"`)
		case '\n':
			builder.WriteString(`\n`)
		case '\r':
			builder.WriteString(`\r`)
		case '\t':
			builder.WriteString(`\t`)
		default:
			if c < 0x20 || c > 0x7e {
				fmt.Fprintf(&builder, `\%03o`, c)
			} else {
				builder.WriteByte(c)
			}
		}
	}
	return builder.String()
}

var generatedEntryPattern = regexp.MustCompile(`\{0x([0-9a-fA-F]{16})ULL, "((?:[^"\\]|\\.)*)"\},`)

// ParseGenerated reads the committed C++ table back into a Corpus, so a test
// (and the resolve command) reads the artifact that ships, not the JSON it was
// generated from.
func ParseGenerated(r io.Reader) (Corpus, error) {
	data, err := io.ReadAll(r)
	if err != nil {
		return nil, err
	}
	corpus := Corpus{}
	for _, match := range generatedEntryPattern.FindAllStringSubmatch(string(data), -1) {
		hash, err := strconv.ParseUint(match[1], 16, 64)
		if err != nil {
			return nil, err
		}
		name, err := cUnescape(match[2])
		if err != nil {
			return nil, err
		}
		corpus[hash] = name
	}
	if len(corpus) == 0 {
		return nil, errors.New("parse: no entries in the generated table")
	}
	return corpus, nil
}

func cUnescape(body string) (string, error) {
	var builder strings.Builder
	for i := 0; i < len(body); i++ {
		c := body[i]
		if c != '\\' {
			builder.WriteByte(c)
			continue
		}
		i++
		if i >= len(body) {
			return "", errors.New("parse: trailing backslash in a name")
		}
		switch body[i] {
		case '\\':
			builder.WriteByte('\\')
		case '"':
			builder.WriteByte('"')
		case 'n':
			builder.WriteByte('\n')
		case 'r':
			builder.WriteByte('\r')
		case 't':
			builder.WriteByte('\t')
		case '0', '1', '2', '3', '4', '5', '6', '7':
			if i+2 >= len(body) {
				return "", errors.New("parse: short octal escape")
			}
			value, err := strconv.ParseUint(body[i:i+3], 8, 8)
			if err != nil {
				return "", fmt.Errorf("parse: bad octal escape %q", body[i:i+3])
			}
			builder.WriteByte(byte(value))
			i += 2
		default:
			builder.WriteByte(body[i])
		}
	}
	return builder.String(), nil
}
