#!/usr/bin/env python3
"""Build the asset-test plugin's payload header from a local game install.

Clones one shipped level's resources (the CGameLevelInfoResource and the CGameLevelResource that share its
name) under a new name: the bytes are the engine's own, with the level's embedded copy of its own name hash
rewritten to the new one. Everything the level references keeps its shipped name, so it resolves from the
game's packages as usual.

  make_payload.py --data <game>/_data/5932408047/rad15/win10 --manifest-id 48037dc70b0ecab2 \
      --source mpl_tutorial_master --name nevr_test_level --out asset_test_payload.h

The repository never carries the game's bytes: this runs against a local install and the header it writes is
not committed.
"""
import argparse
import os
import struct
import sys

sys.dont_write_bytecode = True
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import extract_resource as er  # noqa: E402


def c_array(ident, data):
    lines = ["static const unsigned char %s[%d] = {" % (ident, len(data))]
    for i in range(0, len(data), 16):
        lines.append("    " + ", ".join("0x%02x" % b for b in data[i:i + 16]) + ",")
    lines.append("};")
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--data", required=True)
    ap.add_argument("--manifest-id", required=True)
    ap.add_argument("--source", required=True, help="shipped level name to clone")
    ap.add_argument("--name", required=True, help="the new level name")
    ap.add_argument("--out", required=True)
    args = ap.parse_args()

    repo_root = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))
    hasher = er.load_hash(repo_root)
    type_level = hasher("CGameLevelResourceWin10")
    type_info = hasher("CGameLevelInfoResourceWin10")
    old = hasher(args.source)
    new = hasher(args.name)

    parts = {}
    for label, t in (("kLevelResource", type_level), ("kLevelInfo", type_info)):
        data = bytearray(er.find_resource(args.data, args.manifest_id, t, old))
        old_le = struct.pack("<Q", old)
        new_le = struct.pack("<Q", new)
        hits = 0
        for off in range(0, len(data) - 7):
            if data[off:off + 8] == old_le:
                data[off:off + 8] = new_le
                hits += 1
        sys.stderr.write("%s: rewrote %d embedded copy(ies) of the level name\n" % (label, hits))
        parts[label] = bytes(data)

    with open(args.out, "w") as f:
        f.write("// Generated by plugins/asset-test/tools/make_payload.py from a local install. NOT committed.\n")
        f.write("// Clone of level %s as %s.\n#pragma once\n#include <cstdint>\n\n" % (args.source, args.name))
        f.write("static const uint64_t kTypeLevelResource = 0x%016xULL;\n" % type_level)
        f.write("static const uint64_t kTypeLevelInfo = 0x%016xULL;\n" % type_info)
        f.write("static const uint64_t kLevelName = 0x%016xULL;\n" % new)
        f.write("static const char kLevelNameText[] = \"%s\";\n\n" % args.name)
        f.write(c_array("kLevelResource", parts["kLevelResource"]) + "\n\n")
        f.write(c_array("kLevelInfo", parts["kLevelInfo"]) + "\n")


if __name__ == "__main__":
    main()
